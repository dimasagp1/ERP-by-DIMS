-- SYS-08 Mitra bisnis
CREATE TABLE sys.partner (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(16)   NOT NULL UNIQUE,
    name               VARCHAR(160)  NOT NULL,
    type               VARCHAR(12)   NOT NULL,   -- SUPPLIER / CUSTOMER / BOTH / EXPEDITION
