    version     INTEGER      NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_at  TIMESTAMPTZ,
    updated_by  BIGINT
);

CREATE TABLE sys.location (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    warehouse_id   BIGINT       NOT NULL REFERENCES sys.warehouse(id),
    bin_code       VARCHAR(24)  NOT NULL,
    zone           VARCHAR(24),
    temp_class     VARCHAR(16)  NOT NULL DEFAULT 'AMBIENT',
    is_quarantine  BOOLEAN      NOT NULL DEFAULT FALSE,
    is_b3          BOOLEAN      NOT NULL DEFAULT FALSE,
    active         BOOLEAN      NOT NULL DEFAULT TRUE,
    version        INTEGER      NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by     BIGINT,
    updated_at     TIMESTAMPTZ,
    updated_by     BIGINT,
    UNIQUE (warehouse_id, bin_code)
);

