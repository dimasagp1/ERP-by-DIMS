    updated_at         TIMESTAMPTZ,
    updated_by         BIGINT
);
CREATE INDEX ix_partner_type ON sys.partner (type, active);

-- SYS-09 Gudang, zona & lokasi bin
CREATE TABLE sys.warehouse (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(16)  NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL,
    plant_id    BIGINT       NOT NULL REFERENCES sys.plant(id),
    type        VARCHAR(16)  NOT NULL,           -- RM / PM / FG / SP / GENERAL / TRANSIT
