-- SYS-13 Integrasi & log API
CREATE TABLE sys.integration_log (
    id               BIGINT GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    system           VARCHAR(24)  NOT NULL,      -- HRIS / BSC / ODOO / ABSENSI / TIMBANGAN / WEBHOOK
    direction        VARCHAR(4)   NOT NULL,      -- IN / OUT
    endpoint         VARCHAR(255) NOT NULL,
    ref_doc          VARCHAR(64),
    status           VARCHAR(12)  NOT NULL,      -- PENDING / SUCCESS / FAILED
    http_status      INTEGER,
    request_body     TEXT,
    response_body    TEXT,
    error            TEXT,
    attempts         INTEGER      NOT NULL DEFAULT 0,
    created_at       TIMESTAMPTZ  NOT NULL DEFAULT now(),
    last_attempt_at  TIMESTAMPTZ
);
CREATE INDEX ix_integration_status ON sys.integration_log (status, created_at DESC);

-- SYS-15 Template dokumen, notifikasi & email
