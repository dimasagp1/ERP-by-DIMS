-- Parameter FIN (FIN-99): tarif PPN, toleransi, aturan kredit & anggaran.
CREATE TABLE fin.fin_param (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    key         VARCHAR(32)  NOT NULL UNIQUE,
    value       VARCHAR(64)  NOT NULL,
    description TEXT,
    active      BOOLEAN      NOT NULL DEFAULT TRUE,
    version     INTEGER      NOT NULL DEFAULT 0,
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by  BIGINT,
    updated_at  TIMESTAMPTZ,
    updated_by  BIGINT
);

-- FIN-99 Rekening bank & kas
CREATE TABLE fin.bank_account (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(16)  NOT NULL UNIQUE,
    name            VARCHAR(128) NOT NULL,
    kind            VARCHAR(6)   NOT NULL,      -- BANK / KAS
    bank_name       VARCHAR(64),
    account_no      VARCHAR(40),
    currency_code   VARCHAR(3)   NOT NULL DEFAULT 'IDR',
    gl_account_id   BIGINT       NOT NULL REFERENCES fin.account(id),
    plant_id        BIGINT REFERENCES sys.plant(id),
    active          BOOLEAN      NOT NULL DEFAULT TRUE,
    version         INTEGER      NOT NULL DEFAULT 0,
    created_at      TIMESTAMPTZ  NOT NULL DEFAULT now(),
    created_by      BIGINT,
    updated_at      TIMESTAMPTZ,
    updated_by      BIGINT
);

-- ---------------------------------------------------------------- FIN-10 Faktur supplier
CREATE TABLE fin.ap_invoice (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_no              VARCHAR(40)   NOT NULL UNIQUE,
    plant_id            BIGINT        NOT NULL REFERENCES sys.plant(id),
    doc_date            DATE          NOT NULL,
    status              VARCHAR(12)   NOT NULL,
    partner_id          BIGINT        NOT NULL REFERENCES sys.partner(id),
    supplier_invoice_no VARCHAR(64)   NOT NULL,
    tax_invoice_no      VARCHAR(32),
    due_date            DATE          NOT NULL,
    description         VARCHAR(255),
    source_type         VARCHAR(8)    NOT NULL DEFAULT 'NON_PO',   -- NON_PO / PO (3-way match M2)
    with_ppn            BOOLEAN       NOT NULL DEFAULT TRUE,
    pph_tax_code        VARCHAR(16),
    subtotal            NUMERIC(19,2) NOT NULL DEFAULT 0,
    ppn_amount          NUMERIC(19,2) NOT NULL DEFAULT 0,
    pph_amount          NUMERIC(19,2) NOT NULL DEFAULT 0,
    total               NUMERIC(19,2) NOT NULL DEFAULT 0,
    payable             NUMERIC(19,2) NOT NULL DEFAULT 0,
    advance_payment_id  BIGINT,
    advance_applied     NUMERIC(19,2) NOT NULL DEFAULT 0,
    paid_amount         NUMERIC(19,2) NOT NULL DEFAULT 0,
    submitted_at TIMESTAMPTZ, approved_by BIGINT, approved_at TIMESTAMPTZ, posted_by BIGINT, posted_at TIMESTAMPTZ,
    cancelled_by BIGINT, cancelled_at TIMESTAMPTZ, cancel_reason TEXT,
    version INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by BIGINT,
    updated_at TIMESTAMPTZ, updated_by BIGINT
);
CREATE UNIQUE INDEX ux_ap_supplier_inv ON fin.ap_invoice (partner_id, supplier_invoice_no) WHERE status <> 'CANCELLED';
CREATE INDEX ix_ap_due ON fin.ap_invoice (status, due_date);
CREATE TABLE fin.ap_invoice_line (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id      BIGINT        NOT NULL REFERENCES fin.ap_invoice(id) ON DELETE CASCADE,
    line_no         SMALLINT      NOT NULL,
    account_id      BIGINT        NOT NULL REFERENCES fin.account(id),
    cost_center_id  BIGINT REFERENCES sys.cost_center(id),
    description     VARCHAR(255),
    qty             NUMERIC(19,4) NOT NULL DEFAULT 1,
    unit_price      NUMERIC(19,4) NOT NULL DEFAULT 0,
    amount          NUMERIC(19,2) NOT NULL DEFAULT 0
);

-- ---------------------------------------------------------------- FIN-11/12 Pembayaran hutang & uang muka
