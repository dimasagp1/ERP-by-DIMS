-- Komitmen anggaran dari PR/PO (dipakai mulai M2) dan dokumen biaya lain.
CREATE TABLE fin.budget_commitment (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plant_id         BIGINT        NOT NULL REFERENCES sys.plant(id),
    source_doc_type  VARCHAR(16)   NOT NULL,
    source_doc_id    BIGINT        NOT NULL,
    source_doc_no    VARCHAR(40)   NOT NULL,
    cost_center_id   BIGINT        NOT NULL REFERENCES sys.cost_center(id),
    account_id       BIGINT        NOT NULL REFERENCES fin.account(id),
    period           VARCHAR(6)    NOT NULL,
    amount           NUMERIC(19,2) NOT NULL,
    state            VARCHAR(10)   NOT NULL DEFAULT 'OPEN',   -- OPEN / CONSUMED / RELEASED
    created_at       TIMESTAMPTZ   NOT NULL DEFAULT now()
);
CREATE INDEX ix_commit ON fin.budget_commitment (cost_center_id, account_id, period) WHERE state = 'OPEN';
