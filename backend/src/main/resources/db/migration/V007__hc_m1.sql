    gross            NUMERIC(19,2) NOT NULL DEFAULT 0,
    taxable_gross    NUMERIC(19,2) NOT NULL DEFAULT 0,
    total_deduction  NUMERIC(19,2) NOT NULL DEFAULT 0,
    net              NUMERIC(19,2) NOT NULL DEFAULT 0,
    employer_cost    NUMERIC(19,2) NOT NULL DEFAULT 0,
    pph21            NUMERIC(19,2) NOT NULL DEFAULT 0,
    UNIQUE (run_id, employee_id)
