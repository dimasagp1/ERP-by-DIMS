    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id           BIGINT        NOT NULL REFERENCES hc.payroll_run(id) ON DELETE CASCADE,
    employee_id      BIGINT        NOT NULL REFERENCES hc.employee(id),
    cost_center_id   BIGINT REFERENCES sys.cost_center(id),
    ptkp_status      VARCHAR(5)    NOT NULL,
