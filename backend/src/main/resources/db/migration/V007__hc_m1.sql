CREATE TABLE hc.leave_request (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    doc_no           VARCHAR(40)  NOT NULL UNIQUE,
    plant_id         BIGINT       NOT NULL REFERENCES sys.plant(id),
    doc_date         DATE         NOT NULL,
    status           VARCHAR(12)  NOT NULL,
    employee_id      BIGINT       NOT NULL REFERENCES hc.employee(id),
    leave_type_id    BIGINT       NOT NULL REFERENCES hc.leave_type(id),
    start_date       DATE         NOT NULL,
    end_date         DATE         NOT NULL,
    days             NUMERIC(5,1) NOT NULL DEFAULT 0,
    reason           TEXT,
    delegate_employee_id BIGINT REFERENCES hc.employee(id),
    submitted_at TIMESTAMPTZ, approved_by BIGINT, approved_at TIMESTAMPTZ, posted_by BIGINT, posted_at TIMESTAMPTZ,
    cancelled_by BIGINT, cancelled_at TIMESTAMPTZ, cancel_reason TEXT,
    version INTEGER NOT NULL DEFAULT 0, created_at TIMESTAMPTZ NOT NULL DEFAULT now(), created_by BIGINT,
    updated_at TIMESTAMPTZ, updated_by BIGINT,
    CHECK (end_date >= start_date)
);
CREATE INDEX ix_leave_emp ON hc.leave_request (employee_id, start_date);

-- ---------------------------------------------------------------- HC-08 Lembur (satu dokumen bisa banyak karyawan)
